#!/usr/bin/env node
// Writes src/components/icon-svg.js: the SVG markup of the Iconsax icons the website uses, in
// the variants it uses (Linear, plus Bold where the site shows Bold).
//
// Why (6 Nov 2026): every iconsax-reactjs component carries all six of its variants (Linear,
// Bold, Broken, Bulk, Outline, TwoTone), about 35 KB of gzipped JavaScript on every page for
// glyphs the site never draws. The icons look exactly the same; only the unused variants go.
//
// Run after adding an icon to ICONS below (and using it in src/components/icons.jsx):
//   node scripts/build-icons.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const iconsax = require("iconsax-reactjs");
const { version } = require("iconsax-reactjs/package.json");

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

// Iconsax name -> the variants the site draws. Bold: the check and star marks, WhatsApp, and
// the bottom navigation's selected tab (Home, Services, Projects, Contact, Account).
const BOLD = new Set(["TickCircle", "Star1", "Whatsapp", "Home2", "Category", "Building3", "Call", "User"]);
const ICONS = [
  "ArrowUp", "ArrowRight", "ArrowLeft", "ArrowDown2", "TickCircle", "CloseCircle", "Call", "Setting2", "Like1",
  "Dislike", "Star1", "ArrowRotateLeft", "Add", "MessageText1", "HamburgerMenu", "Location", "Sms", "InfoCircle",
  "GalleryAdd", "Global", "Facebook", "Instagram", "Youtube", "Clock", "Calendar", "Whatsapp", "Paperclip2", "Home2",
  "Category", "Building3", "User", "Lock", "Eye", "EyeSlash", "DocumentText", "LogoutCurve", "Trash", "Edit2",
  "CalendarTick", "SearchNormal1", "Minus", "Wind", "ClipboardTick", "Ruler", "ShoppingCart", "Box", "Lamp",
  "Profile2User",
];

const inner = (name, variant) => {
  const markup = renderToStaticMarkup(React.createElement(iconsax[name], { variant, color: "currentColor" }));
  const match = markup.match(/^<svg[^>]*>([\s\S]*)<\/svg>$/);
  if (!match) throw new Error(`Unexpected markup for ${name} ${variant}`);
  return match[1];
};

const data = {};
for (const name of ICONS) {
  if (!iconsax[name]) throw new Error(`iconsax-reactjs has no ${name}`);
  data[name] = { Linear: inner(name, "Linear"), ...(BOLD.has(name) ? { Bold: inner(name, "Bold") } : {}) };
}

const out = `// Generated by scripts/build-icons.mjs from iconsax-reactjs ${version}. Do not edit by hand.
// The inner SVG markup of each Iconsax icon the site uses, Linear and (where used) Bold.
export const ICON_SVG = ${JSON.stringify(data, null, 1)};
`;
writeFileSync(path.join(root, "src/components/icon-svg.js"), out);
console.log(`${ICONS.length} icons, ${Math.round(out.length / 1024)} KB`);
